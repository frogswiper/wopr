#!/usr/bin/env python3
"""Build public/detailmap.js: a high-resolution inset for the intro zoom (default target Hønefoss).

usage: build-detail.py <out.js> <ne_10m_land> <ne_10m_lakes> <ne_10m_lakes_europe> <ne_10m_rivers_europe>

Natural Earth 1:10m (public domain), clipped to BOX, simplified (Douglas-Peucker) and quantized to 0.01 deg.
Layers: land (rings), lakes (rings), rivers (lines). Coordinates are lon/lat * Q, flattened.
"""
import json, sys

BOX = (3.0, 56.5, 17.5, 65.0)       # lon0, lat0, lon1, lat1: southern Norway, Oslofjord, west Sweden
Q = 100
TOL = 0.006                          # simplification tolerance in degrees (~500 m)

def rings(geom):
    t, c = geom['type'], geom['coordinates']
    if t == 'Polygon': yield from c
    elif t == 'MultiPolygon':
        for p in c: yield from p
def lines(geom):
    t, c = geom['type'], geom['coordinates']
    if t == 'LineString': yield c
    elif t == 'MultiLineString': yield from c

def clip_ring(pts):
    """Sutherland-Hodgman against BOX (fine for filled rendering)."""
    x0, y0, x1, y1 = BOX
    edges = [(lambda p: p[0] >= x0, lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[0] <= x1, lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[1] >= y0, lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0)),
             (lambda p: p[1] <= y1, lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1))]
    out = [tuple(p[:2]) for p in pts]
    for inside, cut in edges:
        if not out: break
        inp, out = out, []
        for i, cur in enumerate(inp):
            prev = inp[i - 1]
            if inside(cur):
                if not inside(prev): out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
    return out

def in_box(p):
    return BOX[0] <= p[0] <= BOX[2] and BOX[1] <= p[1] <= BOX[3]

def dp(pts, tol):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; L = (dx * dx + dy * dy) ** 0.5
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L if L else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            if d > best: best, bi = d, i
        if best > tol:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def enc(pts):
    out, last = [], None
    for x, y in pts:
        q = (round(x * Q), round(y * Q))
        if q != last: out += q; last = q
    return out

out = sys.argv[1]
land, lakes, rivers = [], [], []
for r in (r for f in json.load(open(sys.argv[2]))['features'] for r in rings(f['geometry'])):
    c = clip_ring(r)
    if len(c) > 3:
        s = dp(c + [c[0]], TOL)
        if len(s) > 3: land.append(enc(s))
for fn in sys.argv[3:5]:
    for f in json.load(open(fn))['features']:
        if not f['geometry']: continue
        for r in rings(f['geometry']):
            c = clip_ring(r)
            if len(c) > 3:
                s = dp(c + [c[0]], TOL / 2)
                if len(s) > 3: lakes.append(enc(s))
for f in json.load(open(sys.argv[5]))['features']:
    if not f['geometry']: continue
    for l in lines(f['geometry']):
        seg = []
        for p in l + [None]:
            if p is not None and in_box(p): seg.append(tuple(p[:2])); continue
            if len(seg) > 1: rivers.append(enc(dp(seg, TOL / 2)))
            seg = []
data = {'q': Q, 'box': BOX, 'land': land, 'lakes': lakes, 'rivers': rivers}
with open(out, 'w') as fh:
    fh.write('/* Natural Earth 1:10m inset, southern Norway (public domain, naturalearthdata.com). Generated by tools/build-detail.py */\n')
    fh.write('window.DETAIL=' + json.dumps(data, separators=(',', ':')) + ';\n')
print({k: len(v) for k, v in data.items() if isinstance(v, list)}, 'points', sum(len(x) for k in ('land', 'lakes', 'rivers') for x in data[k]) // 2)
