#!/usr/bin/env python3
"""Build public/worldmap.js from Natural Earth 1:110m GeoJSON (public domain).

usage: build-map.py <ne_110m_land.geojson> <ne_110m_admin_0_countries.geojson> <ne_110m_lakes.geojson> <out.js>

Layers (NORAD big-board colours are applied in the browser):
  land  coastlines of every landmass             (green)
  su    outline of the former Soviet Union, internal borders dissolved  (red)
  us    outline of the United States incl. Alaska  (blue)
  lakes large lakes                              (green)
Coordinates are lon/lat * 4, rounded (0.25 degree grid), flattened [x0,y0,x1,y1,...].
"""
import json, sys
from collections import defaultdict

Q = 4
SOVIET = {'RUS', 'UKR', 'BLR', 'KAZ', 'UZB', 'TKM', 'KGZ', 'TJK', 'GEO', 'ARM', 'AZE', 'MDA', 'LTU', 'LVA', 'EST'}

def rings(geom):
    if geom['type'] == 'Polygon':
        yield from geom['coordinates']
    elif geom['type'] == 'MultiPolygon':
        for poly in geom['coordinates']:
            yield from poly

def quant(ring):
    out = []
    for lon, lat in ring:
        p = (round(lon * Q), round(lat * Q))
        if not out or out[-1] != p:
            out.append(p)
    return out

def flat(pts):
    return [v for p in pts for v in p]

def dissolve(rs):
    """Keep only edges used once (shared internal borders cancel), then chain them into polylines."""
    count = defaultdict(int)
    for r in rs:
        for a, b in zip(r, r[1:]):
            if a != b:
                count[frozenset((a, b))] += 1
    adj = defaultdict(list)
    for e, n in count.items():
        if n == 1:
            a, b = tuple(e)
            adj[a].append(b); adj[b].append(a)
    used = set(); lines = []
    for start in list(adj):
        for nxt in adj[start]:
            if frozenset((start, nxt)) in used:
                continue
            line = [start, nxt]; used.add(frozenset((start, nxt)))
            cur, prev = nxt, start
            while True:
                cand = [p for p in adj[cur] if frozenset((cur, p)) not in used]
                if not cand:
                    break
                p = cand[0]; used.add(frozenset((cur, p))); line.append(p); prev, cur = cur, p
            lines.append(line)
    return lines

land_fc, ctry_fc, lake_fc, out = sys.argv[1:5]
land = [quant(r) for f in json.load(open(land_fc))['features'] for r in rings(f['geometry'])]
land = [r for r in land if len(r) > 3]
us, su = [], []
for f in json.load(open(ctry_fc))['features']:
    code = f['properties'].get('ADM0_A3')
    if code == 'USA':
        us += [quant(r) for r in rings(f['geometry'])]
    elif code in SOVIET:
        su += [quant(r) for r in rings(f['geometry'])]
lakes = [quant(r) for f in json.load(open(lake_fc))['features'] for r in rings(f['geometry'])]
data = {
    'q': Q,
    'land': [flat(r) for r in land],
    'su': [flat(l) for l in dissolve(su) if len(l) > 1],
    'us': [flat(r) for r in us if len(r) > 3],
    'lakes': [flat(r) for r in lakes if len(r) > 3],
}
with open(out, 'w') as fh:
    fh.write('/* Natural Earth 1:110m (public domain, naturalearthdata.com). Generated by tools/build-map.py */\n')
    fh.write('window.WORLD=' + json.dumps(data, separators=(',', ':')) + ';\n')
print({k: (len(v) if isinstance(v, list) else v) for k, v in data.items()}, 'points:', sum(len(x) for k in ('land', 'su', 'us', 'lakes') for x in data[k]) // 2)
